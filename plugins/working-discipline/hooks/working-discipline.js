const NO_DISPATCH_AGENT_TYPES = new Set(['explore', 'plan'])

function canDispatch(event) {
  const t = event && event.agent_type
  if (typeof t !== 'string' || !t) return true
  return !NO_DISPATCH_AGENT_TYPES.has(t.trim().toLowerCase())
}

