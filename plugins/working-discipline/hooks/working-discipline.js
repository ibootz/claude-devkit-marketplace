// 读取 hook 从 stdin 传入的事件 JSON；解析失败时回退为 UserPromptSubmit。
function readEvent() {
  try {
    const raw = fs.readFileSync(0, 'utf8')
    if (!raw || !raw.trim()) return {}
    return JSON.parse(raw)
  } catch (e) {
    return {}
  }
}

