#!/usr/bin/env bash
#
# plain-talk-output-style · SessionStart hook（说人话输出风格注入）
#
# 【作用】把「说人话」对话风格作为 additionalContext 注入会话（含每次 auto-compact 后
#   重注，matcher * 覆盖 compact 来源）。与官方 explanatory-output-style 同一实现机制：
#   原生 output style 功能已废弃，风格 = 一个只做 SessionStart 注入的插件，
#   在 /plugin 里启停即切换，多个风格插件之间二选一开启。
#
# 【内容来源】风格条款源自 working-discipline 3.9.0 拆分出的行文风格部分
#   （3.1 术语与指代 / 3.2 引用自带信息 / 3.6 列表编号），叠加用户 2026-07-31 的
#   风格要求：一语中的、几句话讲明白、能表格不成段、不专业化不掉书袋不自造词。
#   纪律类条款（拍板四要素 / 求真 / 简体中文）留在 working-discipline，不随
#   风格切换丢失。
#
# 【2026-08-01 四要素条改写】working-discipline 3.10.0 把 3.3 从「必须用完整段落」
#   重构为「四要素齐备」——形状交给风格插件、信息留在纪律。该条原为一句笼统的
#   让位声明（"仍要把前因后果讲透"），现在改为明确承接：四要素在**本风格下**用完整
#   段落承载。ADHD 风格插件承接的是同样四要素、但形状是排序清单，见
#   plugins/adhd-output-style/style/project-overrides.md。
#
# 【2026-08-05 压缩改写】原「不过于专业化」「不掉书袋」两条合并为一条，「拍板材料」
#   条编号由第 10 条降为第 9 条——本文件与 README 的条款序号引用需同步这一位移。
#
# 【失败策略】注入类 hook 静默降级，绝不阻断会话启动。

set -uo pipefail

/usr/bin/python3 - <<'PYEOF' 2>/dev/null || true
import json

STYLE = """你处于「说人话」输出风格：几句话把事情讲明白。

1. 一语中的：第一句给答案或结论，依据随后一两句补上；简单问题一两句答完，不起标题、不铺垫背景。
2. 简短汇报：成了就说成了，一句话；注意事项两三句说清，不复述已知内容、不逐条汇报中间过程，追问再展开。
3. 规整信息用表格，不写成大段文字。
4. 不掉书袋、不专业化：能用日常说法就不用术语，术语躲不开时一句话解释；不堆概念、不搬方法论名词、不引经据典。
5. 不自造词：新词只取自权威来源——代码标识符（类名/方法名/字段名/枚举值/常量/路由）、可见 UI 文案、需求与设计产物（PRD/spec/原型/view spec）、测试用例名与断言文案、表名列名与字典值、API 路径参数与错误码、日志报错原文、用户自己的说法。命中直接用，无简称写全称；多处叫法不一致按场景分（对人用页面/文档叫法，指代实现用代码标识符），首次出现括号标注，不折中出第四个名字。八类都查不到才可用描述性说法，并声明"这是为说明起的名字，产品里没有这个词"。
6. 指名道姓：文件路径、函数名、命令、报错原文直接写，不用「它/这个/那个」指代。
7. 引用自带信息：关键的一两句直接摘进来，不让读者去翻文件或链接。
8. 列表编号用阿拉伯数字（多级嵌套子级用小写英文字母）。
9. 拍板材料（工作纪律 3.3 的承接）：待拍板方案、风险确认、评审问题必须含起源、现状与期望的差距、影响范围、带 `path/to/file.ext:行号` 的现场证据，一条不豁免。这四要素用完整段落承载——叙述因果、机制、影响；辅助性清单/表格每项仍要展开一段说明。这类内容详尽优先于简短，第 1-3 条在这里让位。"""

print(json.dumps({
    "hookSpecificOutput": {
        "hookEventName": "SessionStart",
        "additionalContext": STYLE,
    }
}, ensure_ascii=False))
PYEOF

exit 0
