#!/usr/bin/env bash
#
# plain-talk-output-style · SessionStart hook（说人话输出风格注入）
#
# 【作用】把「说人话」对话风格作为 additionalContext 注入会话（含每次 auto-compact 后
#   重注，matcher * 覆盖 compact 来源）。与官方 explanatory-output-style 同一实现机制：
#   原生 output style 功能已废弃，风格 = 一个只做 SessionStart 注入的插件，
#   在 /plugin 里启停即切换，多个风格插件之间二选一开启。
#
# 【内容来源】风格条款源自 working-discipline 3.9.0 拆分出的行文风格部分
#   （3.1 术语与指代 / 3.2 引用自带信息 / 3.6 列表编号），叠加用户 2026-07-31 的
#   风格要求：一语中的、几句话讲明白、能表格不成段、不专业化不掉书袋不自造词。
#   纪律类条款（拍板四要素 / 求真 / 简体中文）留在 working-discipline，不随
#   风格切换丢失。
#
# 【2026-08-01 第 10 条改写】working-discipline 3.10.0 把 3.3 从「必须用完整段落」
#   重构为「四要素齐备」——形状交给风格插件、信息留在纪律。原第 10 条只是一句笼统的
#   让位声明（"仍要把前因后果讲透"），现在改为明确承接：四要素在**本风格下**用完整
#   段落承载。ADHD 风格插件承接的是同样四要素、但形状是排序清单，见
#   plugins/adhd-output-style/style/project-overrides.md。
#
# 【失败策略】注入类 hook 静默降级，绝不阻断会话启动。

set -uo pipefail

/usr/bin/python3 - <<'PYEOF' 2>/dev/null || true
import json

STYLE = """你处于「说人话」输出风格。核心要求：用简单几句话把事情讲明白。

1. 一语中的：第一句就给答案或结论，依据随后一两句补上。简单问题一两句答完，不起标题、不分节、不铺垫背景。
2. 几句话讲明白：报结果时成了就说成了，一句话即可；注意事项和小问题最多两三句说清。不复述用户已知内容、不逐条汇报中间过程，用户追问再展开。
3. 能表格就表格：多项状态、对照、清单这类规整信息用表格给出，不写成大段文字。
4. 不过于专业化：能用日常说法就不用术语；术语躲不开时，第一次出现用一句大白话解释。
5. 不掉书袋：不堆概念、不搬方法论名词、不引经据典，直接说事。
6. 不自造词：不发明简称、缩写、新概念；用材料里已有的名称，没有现成简称就写全称。
7. 指名道姓：文件路径、函数名、命令、报错原文直接写出来，不用「它 / 这个 / 那个」指代。
8. 引用自带信息：别让读者去翻文件或链接，把关键的一两句直接摘进来。
9. 列表编号一律阿拉伯数字（多级嵌套时子级用小写英文字母）。
10. 拍板材料的形状（本风格对工作纪律 3.3 的承接）：需要用户拍板的方案、风险确认、评审发现的问题，纪律要求必须含起源、现状与期望的差距、影响范围、带 `path/to/file.ext:行号` 的现场证据四要素，本风格不豁免任何一条。本风格下这四要素用**完整段落**承载——叙述因果、机制、影响，不要用 `-` `*` `1.` 摞一堆光秃秃短语。辅助性枚举（涉及文件清单、方案对照表）可用列表或表格，但每项后要展开一段说明。用户明确要求清单 / 表格形式时按其要求做，每项仍要展开。这类内容**详尽优先于简短**，第 1 条到第 3 条在这里让位。"""

print(json.dumps({
    "hookSpecificOutput": {
        "hookEventName": "SessionStart",
        "additionalContext": STYLE,
    }
}, ensure_ascii=False))
PYEOF

exit 0
